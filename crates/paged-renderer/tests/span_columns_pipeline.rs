/// Compare every body line of a span-columns-layout sample against
/// InDesign's, case by case.
fn check(
    bytes: &[u8],
    names: &[&str],
    story: impl Fn(u32) -> String,
    frame_of: impl Fn(&str, u32) -> String,
    indesign: &[(usize, &str, f32, f32, char)],
) {
    let doc = idml_import::import_idml_doc(bytes).expect("import");
    let font = inter_font();
    let opts = PipelineOptions {
        font: Some(&font),
        ..PipelineOptions::default()
    };
    let built = pipeline::build_document(&doc, &opts).expect("build");

    let mut report = Vec::new();
    let mut failures = 0;
    for (i, name) in names.iter().enumerate() {
        let seq = i as u32;
        let want: Vec<_> = indesign.iter().filter(|r| r.0 == i).collect();
        let lines = built.story_layout(&story(seq));
        report.push(format!(
            "── {} ({} lines, InDesign {})",
            name,
            lines.len(),
            want.len()
        ));
        if lines.len() != want.len() {
            failures += 1;
        }
        for (k, w) in want.iter().enumerate() {
            let Some(line) = lines.get(k) else {
                report.push(format!("   {:28} missing", w.1));
                continue;
            };
            let x = line
                .clusters
                .iter()
                .map(|c| c.x_pt)
                .fold(f32::INFINITY, f32::min);
            let y = line.baseline_y_pt;
            let id = line.frame_id.clone().unwrap_or_default();
            let frame = if id == frame_of("A", seq) {
                'A'
            } else if id == frame_of("B", seq) {
                'B'
            } else {
                '?'
            };
            let ok = (x - w.2).abs() <= 0.5 && (y - w.3).abs() <= 0.25 && frame == w.4;
            if !ok {
                failures += 1;
            }
            report.push(format!(
                "   {} {:28} engine x {x:7.2} y {y:7.2} {frame}   indesign x {:7.2} y {:7.2} {}",
                if ok { " " } else { "✗" },
                w.1,
                w.2,
                w.3,
                w.4
            ));
        }
    }
    if std::env::var_os("SPAN_COLUMNS_REPORT").is_some() {
        eprintln!(
            "{}",
            report.join(
                "
"
            )
        );
    }
    assert_eq!(
        failures,
        0,
        "
{}",
        report.join(
            "
"
        )
    );
}

#[test]
fn every_line_lands_where_indesign_puts_it() {
    use paged_gen::samples::span_columns::{body_story_id, build, cases, frame_id};
    let bytes = paged_gen::write_idml(&build()).expect("idml");
    let names: Vec<_> = cases().iter().map(|c| c.name).collect();
    check(&bytes, &names, body_story_id, frame_id, INDESIGN);
}

